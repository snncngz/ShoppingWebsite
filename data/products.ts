if (products.length !== 30) {
  throw new Error(`VELORA catalog must contain 30 products, received ${products.length}.`);
}

for (const [category, expected] of Object.entries(expectedCounts)) {
  const actual = getProductsByCategory(category).length;
  if (actual !== expected) {
    throw new Error(`Expected ${expected} products in ${category}, received ${actual}.`);
  }
}

